"""Regenerate the 5 benchmark result tables from all_results_sofar.csv (corrected:
MobileViT rerun, GradientSHAP \\nd where absent) with PVT-v2 and EfficientViT-B2
columns added. Writes LaTeX to paper/results_tables_generated.tex.

Reuses the loader/labels from benchmark_figures.py so tables and figures agree.
"""
import os
import numpy as np
from benchmark_figures import load, grid, MODELS, METHODS  # same corrected data

FAM_ORDER = ["CNN", "Isotropic", "Hierarch.", "Multi-axis", "Hybrid", "Linear"]
FAM_LABEL = {"CNN": "CNN", "Isotropic": "Isotropic", "Hierarch.": "Hierarchical",
             "Multi-axis": "Multi-axis", "Hybrid": "Hybrid", "Linear": "Linear Attn."}
COLLABEL = {"resnet50": "RN-50", "vit_base_patch16_224": "ViT-B/16",
            "swin_base_patch4_window7_224": "Swin-B", "pvt_v2_b2": "PVT-v2",
            "maxvit_small_tf_224": "MaxViT-S", "mobilevitv2_100": "MobileViT",
            "efficientvit_b1": "EffViT-B1", "efficientvit_b2": "EffViT-B2"}
METHFAM = [("Gradient", ["saliency", "integrated_gradients", "input_x_gradient",
                          "smoothgrad", "vargrad", "gradient_shap"]),
           ("CAM", ["grad_cam", "grad_cam_plus_plus"]),
           ("Attention", ["attention_rollout", "attnlrp"]),
           ("Perturb.", ["occlusion", "rise", "lime"])]
MLABEL = {m[0]: m[1] for m in METHODS}


def header():
    # family group multicolumns + cmidrules
    groups, i = [], 0
    fams = [m[2] for m in MODELS]
    while i < len(fams):
        j = i
        while j + 1 < len(fams) and fams[j + 1] == fams[i]:
            j += 1
        groups.append((fams[i], i, j))
        i = j + 1
    top = " & " + " & ".join(
        (f"\\multicolumn{{{b-a+1}}}{{c}}{{\\textbf{{{FAM_LABEL[f]}}}}}") for f, a, b in groups) + " \\\\"
    cmid = " ".join(f"\\cmidrule(lr){{{a+2}-{b+2}}}" for f, a, b in groups)
    sub = "\\textbf{Method} & " + " & ".join(COLLABEL[m[0]] for m in MODELS) + " \\\\"
    return top + "\n    " + cmid + "\n    " + sub


def fmt(v, dec):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "\\nd"
    return f"{v:.{dec}f}"


def table(get, metric, dec, better, caption, label):
    M = grid(get, metric)
    idx = {m[0]: k for k, m in enumerate(METHODS)}
    # column-best (ignore nan)
    best = []
    for j in range(len(MODELS)):
        col = M[:, j]
        vals = col[~np.isnan(col)]
        best.append(None if len(vals) == 0 else (vals.max() if better == "max" else vals.min()))
    lines = [f"\\begin{{table*}}[t]", "  \\centering", f"  \\caption{{{caption}}}",
             f"  \\label{{{label}}}", "  \\setlength{\\tabcolsep}{4pt}",
             "  \\begin{tabular}{l cc cc cc cc}", "    \\toprule", "    " + header(), "    \\midrule"]
    for fi, (fam, mks) in enumerate(METHFAM):
        for mk in mks:
            r = idx[mk]
            cells = []
            for j in range(len(MODELS)):
                v = M[r, j]
                s = fmt(None if np.isnan(v) else v, dec)
                if best[j] is not None and not np.isnan(v) and abs(v - best[j]) < 1e-9:
                    s = f"\\best{{{s}}}"
                cells.append(s)
            lines.append(f"    {MLABEL[mk]} & " + " & ".join(cells) + " \\\\")
        if fi < len(METHFAM) - 1:
            lines.append("    \\midrule")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    get = load()
    specs = [
        ("pointing_game", 2, "max",
         "Localization Family: Pointing Game (PG $\\uparrow$). CAM methods stay strong on CNN, isotropic, hierarchical, and multi-axis backbones but collapse on the linear-attention EfficientViT variants (Grad-CAM $0.55$, Grad-CAM++ $0.44$--$0.56$).",
         "tab:pg"),
        ("max_sensitivity", 3, "min",
         "Robustness Family: Max-Sensitivity (MS $\\downarrow$). Gradient and CAM methods stable on CNNs spike by orders of magnitude on transformers (VarGrad $73.5$ on Swin-B, Grad-CAM++ $17.18$ on ViT-B/16).",
         "tab:ms"),
        ("faithfulness_correlation", 3, "max",
         "Faithfulness Family: Faithfulness Correlation (FC $\\uparrow$). Values cluster near zero across the grid, so at this scale the metric behaves as statistical noise rather than a quality signal.",
         "tab:fc"),
        ("faithfulness_estimate", 3, "max",
         "Faithfulness Family: Faithfulness Estimate (FE $\\uparrow$). More discriminative than FC but sign-flips across architectures, indicating strong sensitivity to the backbone.",
         "tab:fe"),
        ("sparseness", 3, "max",
         "Complexity Family: Sparseness (SP $\\uparrow$). Orders methods by spatial concentration: LIME is sharpest, RISE and Attention Rollout most diffuse. A property of the method, not the backbone.",
         "tab:sp"),
    ]
    out = "% AUTO-GENERATED by scripts/bench/benchmark_tables.py from all_results_sofar.csv\n\n"
    out += "\n".join(table(get, m, d, b, c, l) for m, d, b, c, l in specs)
    os.makedirs("paper", exist_ok=True)
    open("paper/results_tables_generated.tex", "w", encoding="utf-8").write(out)
    print("wrote paper/results_tables_generated.tex")
